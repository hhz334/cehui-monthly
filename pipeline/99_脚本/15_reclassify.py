def norm(text):
    return re.sub(r"[\s\W_]+", "", text or "")


def province_of(title):
    for key, prov in PROVINCE.items():
        if norm(key) in norm(title):
            return prov
    return ""


def level_of(prov, unit, title):
    for key, lv in LEVEL_OVERRIDE.items():
        if norm(key) in norm(title):
            return lv
    if prov == "国际":
        return "国际"
    if prov == "福建":
        return "福建"
    if prov and prov != "全国":
        return "外省"
    return "部级" if any(u in (unit or "") for u in MINISTRY_UNITS) else "行业与官媒"


def main():
    base_path = SNAPSHOT if os.path.exists(SNAPSHOT) else SEL_PATH
    base = json.load(open(base_path, encoding="utf-8"))
    if not os.path.exists(SNAPSHOT):
        save_json(SNAPSHOT, base)

    def hit(title, keys):
        return any(norm(k) in norm(title) for k in keys)

    moved = [s for s in base if hit(s["title"], APPENDIX)]
    kept = [s for s in base if not hit(s["title"], APPENDIX + DROP + MERGE_DROP)]

    for sel in kept:
        title = sel["title"]
        for key, module in MODULE_FIX.items():
            if norm(key) in norm(title):
                sel["module"] = module
        for key, unit in UNIT_FIX.items():
            if norm(key) in norm(title):
                sel["unit"] = unit
        prov = province_of(title)
        if not prov:
            raise SystemExit(f"未标注省份：{title}")
        sel["province"] = prov
        sel["level"] = level_of(prov, sel.get("unit") or sel.get("source_name"), title)

    weekly = load_json(WEEKLY_JSON)
    album = {a["issue"]: a for a in load_json(os.path.join(RAW, "shandong_album.json"))}
    weekly_detail = load_json(os.path.join(RAW, "weekly_detail.json"))
    have = {d["title"] for d in weekly_detail}
    for issue, title, module, prov, unit, priority, keywords, summary in ADD:
        w = next((x for x in weekly if x["issue"] == issue and norm(x["title"]) == norm(title)), None)
        if w is None:
            raise SystemExit(f"周讯第{issue}期缺少条目：{title}")
        meta, url = album[issue], album[issue]["url"]
        publish = (meta.get("publish") or meta.get("date") or "")[:10]
        if title not in have:
            weekly_detail.append({
                "url": url, "final_url": url, "title": title, "title_page": meta["title"],
                "date_page": "", "origin_page": unit, "text": (w.get("body") or "").strip(),
                "http_ok": True, "note": "", "title_sim": 1.0,
                "text_len": len(w.get("body") or ""), "date_ok": True,
                "date_list": publish, "pubtime": publish, "source_id": "weekly",
                "source_name": "《测绘地理信息周讯》", "level": "外省" if prov not in ("全国", "国际") else "部级",
                "carrier": "周讯转载",
            })
        kept.append({
            "module": module, "level": level_of(prov, unit, title), "province": prov, "title": title,
            "source_name": "《测绘地理信息周讯》", "unit": unit, "priority": priority,
            "keywords": keywords, "summary": summary, "carrier": "周讯转载",
            "date_override": publish,
            "note": f"原始来源：{unit}（《测绘地理信息周讯》第{issue}期转载，正文取自该期整期PDF文本层）",
            "match": title,
        })

    save_json(os.path.join(RAW, "weekly_detail.json"), weekly_detail)
    with open(SEL_PATH, "w", encoding="utf-8") as fh:
        json.dump(kept, fh, ensure_ascii=False, indent=1)

    lines = ["# 国家政策文件附录（不计入动态目录）", "",
             "> 以下为自然资源部、国家数据局等国家层面印发的通知、办法、标准、申报指南与政策论述。",
             "> 这类内容属于“公文”而非“测绘动态”，按复核意见从主目录移出，仅作备查与贯彻落实参考。", ""]
    for s in moved:
        lines.append(f"- **{s['title']}**（{s.get('unit','')}｜{s.get('priority','')}）"
                     f"  \n  {s.get('summary','')}")
    with open(APPENDIX_MD, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    from collections import Counter
    deleted = len(base) - len(moved) - (len(kept) - len(ADD))
    print(f"原 {len(base)} 条 → 移入附录 {len(moved)} 条，删除 {deleted} 条，"
          f"新增 {len(ADD)} 条，主目录 {len(kept)} 条")
    print("  模块：", dict(Counter(s["module"] for s in kept)))
    print("  层级：", dict(Counter(s["level"] for s in kept)))
    print("  外省省份：", sorted({s["province"] for s in kept if s["level"] == "外省"}))


if __name__ == "__main__":
    main()
