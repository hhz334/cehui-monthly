def norm(text):
    return re.sub(r"[\s\W_]+", "", text or "")


def main():
    base_path = SNAPSHOT if os.path.exists(SNAPSHOT) else SEL_PATH
    base = json.load(open(base_path, encoding="utf-8"))
    if not os.path.exists(SNAPSHOT):
        save_json(SNAPSHOT, base)

    kept = [s for s in base if not any(norm(k) in norm(s.get("title")) for k in DROP)]
    dropped = len(base) - len(kept)

    weekly = load_json(WEEKLY_JSON)
    album = {a["issue"]: a for a in load_json(os.path.join(RAW, "shandong_album.json"))}
    weekly_detail = []
    new_selections = []
    for issue, title, module, level, unit, priority, keywords, summary in ADD:
        hit = next((w for w in weekly if w["issue"] == issue and norm(w["title"]) == norm(title)), None)
        if hit is None:
            raise SystemExit(f"未在周讯第{issue}期找到条目：{title}")
        meta = album[issue]
        url = meta["url"]
        publish = (meta.get("publish") or meta.get("date") or "")[:10]
        body = (hit.get("body") or "").strip()
        weekly_detail.append({
            "url": url, "final_url": url, "title": title, "title_page": meta["title"],
            "date_page": "", "origin_page": unit, "text": body, "http_ok": True, "note": "",
            "title_sim": 1.0, "text_len": len(body), "date_ok": True,
            "date_list": publish, "pubtime": publish,
            "source_id": "weekly", "source_name": "《测绘地理信息周讯》",
            "level": level, "carrier": "周讯转载",
        })
        new_selections.append({
            "module": module, "level": level, "title": title,
            "source_name": "《测绘地理信息周讯》", "unit": unit, "priority": priority,
            "keywords": keywords, "summary": summary, "carrier": "周讯转载",
            "date_override": publish,
            "note": f"原始来源：{unit}（《测绘地理信息周讯》第{issue}期转载，正文取自该期整期PDF文本层）",
            "match": title,
        })

    merged = kept + new_selections
    save_json(os.path.join(RAW, "weekly_detail.json"), weekly_detail)
    with open(SEL_PATH, "w", encoding="utf-8") as fh:
        json.dump(merged, fh, ensure_ascii=False, indent=1)

    from collections import Counter
    print(f"原 {len(base)} 条 → 删除 {dropped} 条，新增 {len(new_selections)} 条，合计 {len(merged)} 条")
    print("  模块：", dict(Counter(s["module"] for s in merged)))
    print("  属地：", dict(Counter(s["level"] for s in merged)))


if __name__ == "__main__":
    main()
